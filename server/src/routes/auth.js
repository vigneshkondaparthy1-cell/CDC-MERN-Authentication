import {Router} from 'express';
import bcrypt from 'bcryptjs';
import {setSession} from '../config/session.js';
import {z} from 'zod';
import User from '../models/User.js';
import {requireAuth} from '../middleware/auth.js';
const router=Router();
const cookieOptions=()=>({httpOnly:true,secure:process.env.NODE_ENV==='production',sameSite:'lax',path:'/',maxAge:8*60*60*1000});
router.post('/login',async(req,res,next)=>{try{
 const parsed=z.object({email:z.string().trim().email(),password:z.string().min(1)}).safeParse(req.body);
 if(!parsed.success)return res.status(400).json({message:'Enter a valid email and password'});
 const user=await User.findOne({email:parsed.data.email.toLowerCase()}).select('+passwordHash +sessionVersion');
 if(!user||!await bcrypt.compare(parsed.data.password,user.passwordHash))return res.status(401).json({message:'Invalid email or password'});
 if(user.active===false)return res.status(403).json({message:'Your account has been deactivated. Please contact an administrator.'});
 setSession(res,user);
 res.json({user:user.toJSON()});
}catch(e){next(e)}});
router.post('/logout',(_req,res)=>res.clearCookie('cdc_token',{path:'/',httpOnly:true,secure:process.env.NODE_ENV==='production',sameSite:'lax'}).json({message:'Logged out'}));
router.get('/me',requireAuth,(req,res)=>res.json({user:req.user}));
export default router;
