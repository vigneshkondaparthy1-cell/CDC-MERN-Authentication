const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const dotenv=require('dotenv');
const envPath=path.join(__dirname,'.env');
const local=path.join(__dirname,'..','.local');
fs.mkdirSync(local,{recursive:true});
const original=fs.existsSync(envPath)?fs.readFileSync(envPath,'utf8'):'';
if(original&&!fs.existsSync(path.join(local,'previous.env')))fs.writeFileSync(path.join(local,'previous.env'),original);
const env=dotenv.parse(original);
env.MONGO_URI='mongodb://127.0.0.1:27017/cdc_auth';
if(!env.JWT_SECRET||env.JWT_SECRET.length<32||/REPLACE/.test(env.JWT_SECRET))env.JWT_SECRET=crypto.randomBytes(32).toString('hex');
if(!env.ADMIN_PASSWORD||env.ADMIN_PASSWORD.length<8||/REPLACE/.test(env.ADMIN_PASSWORD))env.ADMIN_PASSWORD=crypto.randomBytes(12).toString('base64url');
env.ADMIN_EMAIL=env.ADMIN_EMAIL||'admin@example.com';
env.ADMIN_NAME=env.ADMIN_NAME||'Administrator';
env.PORT='5000';env.CLIENT_ORIGIN='http://localhost:5173';env.NODE_ENV='development';
fs.writeFileSync(envPath,Object.entries(env).map(([k,v])=>`${k}=${JSON.stringify(v)}`).join('\n')+'\n');
fs.writeFileSync(path.join(local,'LOGIN.txt'),`CDC Portal local Admin login\n\nURL: http://localhost:5173\nEmail: ${env.ADMIN_EMAIL}\nPassword: ${env.ADMIN_PASSWORD}\n\nKeep this file private.\n`);
console.log('Local configuration saved. Login details: .local/LOGIN.txt');
